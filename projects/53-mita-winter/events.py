from timeline import ON, END, AD_STOP, DUR
from words import WORDS


def at(word, n=0, after=0.0):
    w0 = word.lower().replace('ё', 'е')
    hits = [s for w, s, e, _ in WORDS if w.lower().strip('.,!?…:;«»').replace('ё', 'е') == w0 and s >= after - 1e-6]
    return hits[n]


