def tts_text(take):
    clip = next(c for c in CLIPS if c[1] == take)
    text = clip[5][2:] if clip[5].startswith('— ') else clip[5]
    text = text.replace('] — ', '] ')
    if text.startswith('['):
        return text
    return TAGS.get(take, '') + text


def subtitle(clip):
    import re
    return re.sub(r'\[[^\]]*\]\s*', '', clip[5]).strip()


