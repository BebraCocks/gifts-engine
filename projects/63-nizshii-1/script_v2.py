def tts_text(take):
    clip = next(c for c in CLIPS if c[1] == take)
    text = clip[5].replace('— ', '', 1) if clip[5].startswith('— ') else clip[5]
    text = text.replace('] — ', '] ')
    if text.startswith('['):                          # теги уже вписаны в сам текст
        return text
    return TAGS.get(take, '') + text


def subtitle(clip):
    import re
    return re.sub(r'\[[^\]]*\]\s*', '', clip[5]).strip()


